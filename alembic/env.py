"""Alembic environment. The URL comes from the caller (restock.runtime.alembic_config) or from
DATABASE_URL, so the same migrations run on SQLite and PostgreSQL.

Alembic runs this file for every command that touches the database (`restock migrate`, the
tests' upgrade and downgrade, or `alembic ...` by hand). The module-level code below picks
the database; then one of the two functions runs the migrations in alembic/versions: online
(the usual case) connects and executes them, offline (`alembic upgrade head --sql`) prints
the SQL instead.
"""

import logging

from alembic import context

from restock.runtime import Settings, make_engine
from restock.schemas import Base

config = context.config
# restock.runtime.alembic_config() passes the URL in config.attributes; plain `alembic` does not,
# and then the URL comes from DATABASE_URL like the app's.
database_url = config.attributes.get("database_url") or Settings().database_url
if "database_url" not in config.attributes and not logging.getLogger().handlers:
    # Plain `alembic ...` on the command line; `restock migrate` configures JSON logging itself.
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s %(message)s")


def run_migrations_offline() -> None:
    # No database connection: the SQL is printed, with every value written into it.
    context.configure(
        url=database_url,
        target_metadata=Base.metadata,
        literal_binds=True,
        render_as_batch=database_url.startswith("sqlite"),
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    # The app's own engine setup (restock.runtime), so SQLite gets the same BEGIN handling.
    engine = make_engine(database_url)
    try:
        with engine.connect() as connection:
            context.configure(
                connection=connection,
                # The models, which `alembic revision --autogenerate` compares the database
                # with.
                target_metadata=Base.metadata,
                # SQLite cannot alter most of a table in place, so autogenerated changes for it
                # are written as batch operations, which copy the table.
                render_as_batch=connection.dialect.name == "sqlite",
                # restock.runtime takes BEGIN over from the sqlite3 driver, so DDL is transactional
                # on SQLite too and a failed upgrade rolls back completely.
                transactional_ddl=True,
            )
            with context.begin_transaction():
                context.run_migrations()
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
